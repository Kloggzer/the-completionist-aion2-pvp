/** Every connected node set containing the starts, by brute force (tiny graphs only). */
function bruteBest(g: Graph, budget: number) {
  let best = 0
  const n = g.nodes.length
  for (let m = 0; m < 1 << n; m++) {
    const s = new Set<number>()
    for (let i = 0; i < n; i++) if (m & (1 << i)) s.add(i)
    if (!g.starts.every(x => s.has(x)) || !connected(g, s)) continue
    let c = 0
    for (const i of s) c += g.nodes[i].cost
    const v = setValue(g, s)
    if (c <= budget && v > best) best = v
  }
  return best
}

