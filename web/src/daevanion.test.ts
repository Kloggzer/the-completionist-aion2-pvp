describe('Daevanion optimizer', () => {
  // S . A          start in the middle row; the valuable node B sits behind a worthless, expensive gate
  // x G B
  // C . .
  const tiny = buildGraph([{ b: 1, nodes: [
    { r: 0, c: 0, cost: 0, v: 0, start: true }, { r: 0, c: 2, cost: 1, v: 1 }, { r: 0, c: 1, cost: 1, v: 0.2 },
    { r: 1, c: 0, cost: 1, v: 0.1 }, { r: 1, c: 1, cost: 3, v: 0 }, { r: 1, c: 2, cost: 2, v: 9 }, { r: 2, c: 0, cost: 1, v: 1.5 },
  ] }])

  it('matches brute force on a small board for every budget', () => {
    for (let b = 0; b <= 9; b++) {
      const p = optimize(tiny, b)
      expect(p.spent).toBeLessThanOrEqual(b)
      expect(connected(tiny, p.owned)).toBe(true)
      expect(p.value).toBeCloseTo(bruteBest(tiny, b), 6)
    }
  })

  it('returns a buy order in which every node touches an owned one', () => {
    const p = optimize(tiny, 9), have = new Set(tiny.starts)
    for (const i of p.order) { expect(tiny.adj[i].some(j => have.has(j))).toBe(true); have.add(i) }
    expect(have).toEqual(p.owned)
  })

  it('skill groups with a specialization step (worth only from the second level on), matching brute force', () => {
    const curve = [0, 0.5, 6, 6.5]
    const g = buildGraph([{ b: 1, nodes: [
      { r: 0, c: 0, cost: 0, v: 0, start: true }, { r: 0, c: 1, cost: 3, v: 0, grp: 0 }, { r: 0, c: 2, cost: 3, v: 0, grp: 0 },
      { r: 0, c: 3, cost: 3, v: 0, grp: 0 }, { r: 1, c: 0, cost: 1, v: 1.2 }, { r: 2, c: 0, cost: 1, v: 1.2 },
    ] }], [k => curve[k]])
    for (let b = 0; b <= 11; b++) expect(optimize(g, b).value, 'budget ' + b).toBeCloseTo(bruteBest(g, b), 6)
  })

  it('keeps locked nodes in "add" mode', () => {
    const locked = new Set([0, 3, 6])
    const p = optimize(tiny, 2, locked)
    for (const i of locked) expect(p.owned.has(i)).toBe(true)
    expect(p.spent).toBeLessThanOrEqual(2)
  })

  it.skipIf(!has)('comes within 1 % of a proven optimum on a real board where the greedy alone is 10 % short', () => {
    // Gladiator Nezekan, 40 points, seeded random node values; optimum 34.49 proven with the HiGHS MIP (flow model)
    let s = 7
    const R = () => (s = s * 16807 % 2147483647) / 2147483647
    const nodes = D.classes['1'].boards['1'].nodes.map(n => ({ r: n[0], c: n[1], cost: n[2], start: n[3] === 0, v: n[3] === 1 ? n[2] * (0.5 + R()) * (n[2] === 1 ? 0.3 : 1) : 0, grp: n[3] === 2 ? n[4] as number : undefined }))
    const order: number[] = [], size = new Map<number, number>()
    for (const n of nodes) if (n.grp != null) { if (!order.includes(n.grp)) order.push(n.grp); size.set(n.grp, (size.get(n.grp) || 0) + 1) }
    const vals = new Map<number, number[]>()
    for (const g of order) vals.set(g, Array.from({ length: size.get(g)! }, (_, j) => 1.5 + (j === 1 ? 6 * R() : 0)))
    const g = buildGraph([{ b: 1, nodes }], Array.from({ length: Math.max(...order) + 1 }, (_, k) => (n: number) => (vals.get(k) || []).slice(0, n).reduce((a, b) => a + b, 0)))
    const greedy = optimize(g, 40, undefined, 0), searched = optimize(g, 40)
    expect(greedy.value).toBeLessThan(34.49 * 0.95)
    expect(searched.value).toBeGreaterThan(34.49 * 0.99)
    expect(connected(g, searched.owned)).toBe(true)
  })
})

describe.skipIf(!has)('Daevanion value model', () => {
  const ctx = (cls = '1', mode: 'pve' | 'pvp' = 'pve', w = W(cls)): Ctx => modelCtx(D.classes[cls], cls, mode, w)
  const lv = (cls = '1') => D.classes[cls].skills.map(() => 12)
  const gain = (c: Ctx, d: Totals, t = T) => {
    const e0 = evaluate(t, lv(), c), e = evaluate({ ...t, ...Object.fromEntries(Object.entries(d).map(([k, v]) => [k, (t[k as keyof Totals] || 0) + v!])) }, lv(), c)
    return { dmg: (e.dmg / e0.dmg - 1) * 100, ehp: (e.ehp / e0.ehp - 1) * 100 }
  }

  it('offensive stats land in the range of the mmoherald guide', () => {
    const c = ctx()
    // guide (KR endgame): +1 % Double 0.6–0.8, Attack increase 0.76, Combat Speed 0.74, Damage Boost 0.3–0.62, Weapon 0.5–0.62
    expect(gain(c, { double: 1 }).dmg).toBeGreaterThan(0.5); expect(gain(c, { double: 1 }).dmg).toBeLessThan(1)
    expect(gain(c, { speed: 1 }).dmg).toBeGreaterThan(0.6); expect(gain(c, { speed: 1 }).dmg).toBeLessThan(0.9)
    expect(gain(c, { dmg: 1 }).dmg).toBeGreaterThan(0.3); expect(gain(c, { dmg: 1 }).dmg).toBeLessThan(0.7)
    expect(gain(c, { perfect: 1 }).dmg).toBeLessThan(0.15)
    expect(gain(c, { atkBonus: 10 }).dmg).toBeLessThan(gain(c, { atk: 10 }).dmg) // attack bonus comes after the weapon boost
    expect(gain(c, { hp: 100 }).dmg).toBe(0)
  })

  it('crit at the cap is worth nothing, below it something', () => {
    const c = ctx()
    expect(rates({ ...T, crit: 5000 }, c).crit).toBe(0.5)
    expect(gain(c, { crit: 50 }, { ...T, crit: 5000 }).dmg).toBe(0)
    expect(gain(c, { crit: 50 }, { ...T, crit: 600 }).dmg).toBeGreaterThan(0)
  })

  it('defense takes off 10 % per hit in PvE, 1 % in PvP', () => {
    const pve = gain(ctx('1', 'pve'), { def: 500 }).ehp, pvp = gain(ctx('1', 'pvp'), { def: 500 }).ehp
    expect(pve).toBeGreaterThan(pvp * 5)
    expect(gain(ctx('1', 'pvp'), { pvpDef: 500 }).ehp).toBeGreaterThan(0)
    expect(gain(ctx('1', 'pve'), { pvpDef: 500 }).ehp).toBe(0)
  })

  it('every skill level of a rotation skill counts, from the per-level data', () => {
    const c = ctx(), sk = D.classes['1'].skills, si = sk.findIndex(s => s.en === 'Overhead Slam')
    expect(c.skills[si].w).toBeGreaterThan(0)
    const at = (l: number) => { const x = lv(); x[si] = l; return evaluate(T, x, c).dmg }
    for (let l = 10; l < 20; l++) expect(at(l + 1)).toBeGreaterThan(at(l))
    // a passive by its level table: Attack Preparation adds PvE damage boost and defense per level
    const ap = sk.findIndex(s => s.en === 'Attack Preparation'), x = lv(); x[ap]++
    expect(evaluate(T, x, c).dmg).toBeGreaterThan(evaluate(T, lv(), c).dmg)
    expect(evaluate(T, x, c).ehp).toBeGreaterThan(evaluate(T, lv(), c).ehp)
  })

  it('a skill taken out of the rotation is worth nothing', () => {
    const sk = D.classes['1'].skills, si = sk.findIndex(s => s.en === 'Overhead Slam')
    const c = ctx('1', 'pve', W('1', { use: { 'Overhead Slam': false } })), x = lv(); x[si]++
    expect(evaluate(T, x, c).dmg).toBeCloseTo(evaluate(T, lv(), c).dmg, 9)
    expect(defaultUse('2', D.classes['2'].skills.find(s => s.en === 'Flash Rampage')!)).toBe(false)
  })
})

