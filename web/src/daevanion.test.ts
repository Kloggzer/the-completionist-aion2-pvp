  it('spends exactly the points, stays connected and gains with more points', () => {
    set({})
    let last = -1
    for (const free of [0, 30, 120, 300]) {
      const x = poolInput(D, '7', 'pve', 'respec', free), p = solve({ ...x.inp, iters: 60 })
      expect(p.spent).toBe(free) // exactly the player's points
      expect(connected(x.g, new Set(p.owned))).toBe(true)
      expect(p.score).toBeGreaterThanOrEqual(last - 1e-9)
      last = p.score
    }
    reset()
  })

  it('the damage goal buys more damage, the defensive goal more effective HP', () => {
    const run = (off: number) => {
      set({ off: { 1: off } })
      const x = poolInput(D, '1', 'pve', 'respec', 120), p = solve({ ...x.inp, iters: 60 }), r = evalSet(x.inp, p.owned)
      reset()
      return { dmg: r.e.dmg / r.e0.dmg, ehp: r.e.ehp / r.e0.ehp }
    }
    const dmg = run(1), def = run(0)
    expect(dmg.dmg).toBeGreaterThan(def.dmg)
    expect(def.ehp).toBeGreaterThan(dmg.ehp)
  })

  it('respec is never worse than adding to the current board with the same points', () => {
    set({ off: { 7: 0 } })
    const x0 = poolInput(D, '7', 'pve', 'respec', 100), old = solve({ ...x0.inp, iters: 40 })
    const open: Record<string, number[]> = {}
    for (const i of old.owned) { const r = x0.refs[i]; if (r.n[3]) (open[r.slot] ||= []).push(r.n[0] * 32 + r.n[1]) }
    set({ off: { 7: 1 } }, { daeLive: { Standard: { at: 1, cls: '7', level: 45, open } } })
    const total = old.spent + 20, add = poolInput(D, '7', 'pve', 'add', total), re = poolInput(D, '7', 'pve', 'respec', total)
    expect(re.spentNow).toBe(old.spent)
    expect(add.budget).toBe(20) // only the free points
    expect(re.budget).toBe(total) // everything
    const pa = solve({ ...add.inp, iters: 40 }), pr = solve({ ...re.inp, iters: 40 })
    // both scored against the same base (the character without this pool's nodes)
    expect(evalSet(re.inp, pr.owned).score).toBeGreaterThanOrEqual(evalSet(add.inp, pa.owned).score - 1e-6)
    for (const i of add.cur) expect(pa.owned.includes(i)).toBe(true)
    reset()
  })

  it('pinned nodes: "want" is bought with its path, "never" not', () => {
    set({})
    const x = poolInput(D, '1', 'pve', 'respec', 40), free = solve({ ...x.inp, iters: 40 })
    // the farthest Unique corner of Nezekan (not in a 40-point plan) and the plan's best node
    const corner = x.refs.findIndex((r, i) => r.slot === '1' && r.n[2] === 4 && !free.owned.includes(i))
    const banned = free.owned.find(i => !x.g.starts.includes(i))!
    const p = solve({ ...x.inp, want: [corner], ban: [banned], iters: 40 })
    expect(p.owned).toContain(corner)
    expect(p.owned).not.toContain(banned)
    expect(p.spent).toBeLessThanOrEqual(40)
    expect(connected(x.g, new Set(p.owned))).toBe(true)
    reset()
  })

  it('skill level without Daevanion = website level minus the open skill nodes', () => {
    const c = D.classes['7'], si = c.skills.findIndex(s => s.en === 'Bolt')
    const open: Record<string, number[]> = {}
    for (const [slot, b] of Object.entries(c.boards)) for (const n of b.nodes) if (n[3] === 2 && n[4] === si) (open[slot] ||= []).push(n[0] * 32 + n[1])
    const skills = parseSkills({ skill: { skillList: [{ category: 'Active', name: 'Bolt', skillLevel: 14 }, { category: 'Dp', name: 'X', skillLevel: 3 }] } })
    expect(skills).toEqual({ Bolt: 14 })
    const bases = skillBases(c, { at: 1, cls: '7', level: 45, open, skills }, W('7'))
    expect(bases[si]).toEqual({ lv: 10, src: 'page' })
    expect(bases[(si + 1) % c.skills.length].src).toBe('guess')
  })

  it('names worthless owned dead ends (MP) in the advice', () => {
    const c = D.classes['7'], mp = D.stats.findIndex(s => s.key === 'MP'), b = c.boards['1']
    // an MP node next to the start
    const isMp = (n: (typeof b.nodes)[number]) => n[3] === 1 && (n[4] as [number, number][]).every(([x]) => x === mp)
    const start = b.nodes.find(n => n[3] === 0)!, node = b.nodes.find(n => isMp(n) && Math.abs(n[0] - start[0]) + Math.abs(n[1] - start[1]) === 1)
    if (!node) return
    set({ free: 0 }, { daeLive: { Standard: { at: 1, cls: '7', level: 45, open: { 1: [node[0] * 32 + node[1]] } } } })
    const [pve] = advice()
    expect(pve.pool).toBe('pve')
    expect(pve.dead).toBe(1)
    expect(pve.respec).toBeGreaterThanOrEqual(pve.add - 1e-6)
    reset()
  })

  it('leaves out boards above the character level', () => {
    expect(poolSlots(D.classes['7'], 'pve', 25)).toEqual(['1', '2'])
    expect(poolSlots(D.classes['7'], 'pvp', 44)).toEqual([])
    expect(poolSlots(D.classes['7'], 'ariel', 45)).toEqual(['5'])
  })
